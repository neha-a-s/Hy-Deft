def calculate_sift_features(images, orientations=9, pixels_per_cell=(8, 8), cells_per_block=(2, 2), block_norm='L2-Hys'):
    """
    Calculate sift features for a set of images.

    Parameters:
        images (torch.Tensor or np.ndarray): A batch of images with shape (batch_size, height, width, channels) or (batch_size, channels, height, width).
        orientations (int): Number of orientation bins for sift.
        pixels_per_cell (tuple): Size (in pixels) of a cell.
        cells_per_block (tuple): Number of cells per block.
        block_norm (str): Block normalization method.

    Returns:
        np.ndarray: sift features for all images, shape (batch_size, sift_feature_size).
    """
    if isinstance(images, torch.Tensor):
        images = images.detach().permute(0, 2, 3, 1).numpy()  # Convert to (batch_size, height, width, channels)

    sift_features = []
    for img in images:
        # Convert to grayscale if necessary
        if img.shape[-1] == 3:  # Check if the image has 3 channels
            gray_img = rgb2gray(img)
        else:
            gray_img = img.squeeze()  # For single-channel images

        # Calculate sift features
        features = sift(
            gray_img,
            orientations=orientations,
            pixels_per_cell=pixels_per_cell,
            cells_per_block=cells_per_block,
            block_norm=block_norm,
            visualize=False
        )
        sift_features_tensor = torch.tensor(features, dtype=torch.float32)
        sift_features_tensor = feature_projector_sift(sift_features_tensor)
        sift_features.append(sift_features_tensor)

    return np.array(sift_features)

