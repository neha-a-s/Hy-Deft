def compute_sift_features(loader):
    sift_features = []
    labels = []
    sift = cv2.SIFT_create()  # Create a SIFT detector

    for images, targets in loader:
        # Convert to NumPy array and process batch
        images_np = images.permute(0, 2, 3, 1).numpy()  # Convert to (batch, H, W, C)
        for img, label in zip(images_np, targets):
            # Check if the image has 3 channels (RGB)
            if img.shape[-1] == 3:
                # Convert to grayscale if it's RGB
                gray_img = rgb2gray(img)
            else:
                # If it's already grayscale, just squeeze the channel dimension
                gray_img = img.squeeze()

            # Convert image to uint8 format (required for SIFT)
            gray_img = (gray_img * 255).astype(np.uint8)

            # Compute SIFT keypoints and descriptors
            keypoints, descriptors = sift.detectAndCompute(gray_img, None)

            if descriptors is not None:
                # Flatten descriptors into a single feature vector
                feature_vector = descriptors.flatten()

                # Limit the feature vector to a fixed size (e.g., 512), padding with zeros if necessary
                fixed_size = 512
                if len(feature_vector) > fixed_size:
                    feature_vector = feature_vector[:fixed_size]
                else:
                    feature_vector = np.pad(feature_vector, (0, fixed_size - len(feature_vector)))

                sift_features.append(feature_vector)
                labels.append(label.item())
            else:
                # If no descriptors are found, append a zero feature vector
                sift_features.append(np.zeros(512))
                labels.append(label.item())

    return np.array(sift_features), np.array(labels)

