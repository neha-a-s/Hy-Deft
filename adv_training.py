def train(model, device, train_loader, optimizer, epsilon):
    model.train()
    total_loss = 0
    for data, target in train_loader:
        data, target = data.to(device), target.to(device)

        # Reshape target to be a 1D tensor
        target = target.reshape(-1)  # or target = target.squeeze() if it's a column vector
        #print(target.shape)

        # Create adversarial examples
        perturbed_data = fgsm_attack(model, data, target, epsilon)

        optimizer.zero_grad()
        output_clean = model(data)

        # Calculate loss using the reshaped target
        loss_clean = nn.CrossEntropyLoss()(output_clean, target)

        output_adv = model(perturbed_data)
        loss_adv = nn.CrossEntropyLoss()(output_adv, target)

        loss = loss_clean + loss_adv  # Combined loss for both examples
        loss.backward()
        optimizer.step()

        total_loss += loss.item()

    avg_loss = total_loss / len(train_loader)
    return avg_loss

