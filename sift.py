def pgd_attack(model, images, labels, epsilon, alpha, steps, device):
    # Clone the original images to start the attack
    adv_images = images.clone().detach().to(device).requires_grad_(True)
    labels = labels.to(device)
    features = calculate_sift_features(adv_images)
    features = torch.tensor(features, device=device)

    for _ in range(steps):
        # Zero the gradient
        # Transform the features and move to device
        transformed_features = calculate_sift_features(adv_images)
        transformed_features = torch.tensor(transformed_features, device=device, dtype=torch.float32)
        #print("transformed_features.shape", transformed_features.shape)
        adv_images.requires_grad = True
        outputs = model(adv_images, features)
        loss = torch.nn.CrossEntropyLoss()(outputs, labels)
        loss.backward()

        # Update adversarial images
        adv_images = adv_images + alpha * adv_images.grad.sign()
        adv_images = torch.clamp(adv_images, 0, 1)  # Ensure pixels are valid
        perturbation = torch.clamp(adv_images - images, -epsilon, epsilon)
        adv_images = torch.clamp(images + perturbation, 0, 1).detach()  # Apply perturbation

    return adv_images, transformed_features

def bim_attack(model, images, labels, epsilon, alpha, steps, device):
    # BIM is similar to PGD without the random start
    return pgd_attack(model, images, labels, epsilon, alpha, steps, device)

def cw_attack(model, images, labels, c, lr, steps, device):
    adv_images = images.clone().detach().to(device).requires_grad_(True)
    labels = labels.to(device)
    features = calculate_sift_features(adv_images)
    features = torch.tensor(features, device=device)

    optimizer = torch.optim.Adam([adv_images], lr=lr)

    for _ in range(steps):
        outputs = model(adv_images, features)
        one_hot_labels = torch.eye(outputs.shape[1])[labels].to(device)

        # Compute Carlini-Wagner loss
        real = (one_hot_labels * outputs).sum(1)
        other = ((1 - one_hot_labels) * outputs - one_hot_labels * 1e4).max(1)[0]
        cw_loss = torch.clamp(other - real, min=-1).sum()

        # L2 loss to ensure perturbations are minimal
        l2_loss = torch.norm(adv_images - images, p=2)

        # Total loss
        loss = cw_loss + c * l2_loss
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        # Clamp images to ensure valid pixel range
        adv_images = torch.clamp(adv_images, 0, 1).detach().requires_grad_(True)

    return adv_images, features

def evaluate_attacks(test_loader, model, device, transformer, attack_fn, **attack_params):
    model.eval()
    correct = 0
    total = 0

    for images, labels, features in test_loader:
        # Move to device
        images = images.to(device)
        labels = labels.to(device)
        labels = labels.reshape(-1)
        # features = features.to(device)  # No need to move original features


        # Generate adversarial examples
        adv_images, features_adv = attack_fn(model, images, labels, device=device, **attack_params)

        # Evaluate the model on adversarial examples
        outputs = model(adv_images, features_adv)
        _, predicted = torch.max(outputs, 1)

        total += labels.size(0)
        correct += (predicted == labels).sum().item()

        if total == 128:
          break

    # Compute accuracy
    return correct / total

