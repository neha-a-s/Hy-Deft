class DermaMNISTWithSIFT(Dataset):
    def __init__(self, original_dataset, fixed_size=512):
        self.original_dataset = original_dataset
        self.fixed_size = fixed_size  # Fixed size for feature vector
        self.sift = cv2.SIFT_create()  # Initialize SIFT detector

    def __len__(self):
        return len(self.original_dataset)

    def __getitem__(self, idx):
        # Get image and label
        image, label = self.original_dataset[idx]

        # Convert image to NumPy array and compute SIFT features
        image_np = image.permute(1, 2, 0).numpy()  # Convert to (H, W, C)
        # Check if the image has 3 channels (RGB)
        if image_np.shape[-1] == 3:
            # Convert to grayscale if it's RGB
            gray_img = rgb2gray(image_np)
        else:
            # If it's already grayscale, just squeeze the channel dimension
            gray_img = image_np.squeeze()

        gray_img = (gray_img * 255).astype(np.uint8)  # Convert to uint8

        # Compute SIFT keypoints and descriptors
        keypoints, descriptors = self.sift.detectAndCompute(gray_img, None)

        if descriptors is not None:
            # Flatten descriptors into a single feature vector
            feature_vector = descriptors.flatten()

            # Limit the feature vector to the fixed size, padding with zeros if necessary
            if len(feature_vector) > self.fixed_size:
                feature_vector = feature_vector[:self.fixed_size]
            else:
                feature_vector = np.pad(feature_vector, (0, self.fixed_size - len(feature_vector)))
